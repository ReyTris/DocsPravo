export async function classify(provider: LLMProvider, ocrText: string): Promise<ClassifyOutput> {
  const messages = FEW_SHOT.flatMap((ex) => [
    { role: "user" as const, content: ex.user },
    { role: "assistant" as const, content: JSON.stringify(ex.assistant) },
  ]);
  messages.push({ role: "user" as const, content: ocrText });

  const result = await provider.complete({
    system: SYSTEM,
    messages,
    schema: ClassifyOutputSchema,
    schemaName: "ClassifyOutput",
    temperature: 0,
  });
  return result.data;
}
