export async function summarizeYellow(
  provider: LLMProvider,
  navigator: NavigatorOutput,
  ocrText: string,
): Promise<YellowSummaryOutput> {
  const userInput = (nav: NavigatorOutput, text: string) =>
    `=== ДАННЫЕ НАВИГАТОРА ===
${JSON.stringify(nav, null, 2)}

=== ИСХОДНЫЙ ТЕКСТ ДОКУМЕНТА (OCR + маскирование ПД) ===
${text}`;

  const result = await provider.complete({
    system: SYSTEM,
    messages: [
      { role: "user", content: userInput(FEW_SHOT_NAV, FEW_SHOT_TEXT) },
      { role: "assistant", content: JSON.stringify(FEW_SHOT_OUTPUT) },
      { role: "user", content: userInput(navigator, ocrText) },
    ],
    schema: YellowSummaryOutputSchema,
    schemaName: "YellowSummaryOutput",
    temperature: 0,
  });
  return result.data;
}
