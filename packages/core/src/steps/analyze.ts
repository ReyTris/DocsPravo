export async function analyze(provider: LLMProvider, ext: ExtractOutput): Promise<AnalysisOutput> {
  const result = await provider.complete({
    system: SYSTEM,
    messages: [
      { role: "user", content: JSON.stringify(FEW_SHOT_INPUT_EXTRACT) },
      { role: "assistant", content: JSON.stringify(FEW_SHOT_OUTPUT) },
      { role: "user", content: JSON.stringify(ext) },
    ],
    schema: AnalysisOutputSchema,
    schemaName: "AnalysisOutput",
    temperature: 0.2,
  });
  return result.data;
}
