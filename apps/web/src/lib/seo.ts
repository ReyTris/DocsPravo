/**
 * Хелпер для страниц: задаёт title по шаблону и базовые поля,
 * чтобы каждая страница не дублировала boilerplate.
 */
export function buildMetadata(input: {
  title: string;
  description?: string;
  path: string;
  noIndex?: boolean;
  keywords?: string[];
}): Metadata {
  const url = `${SITE_URL}${input.path}`;
  const description = input.description ?? SITE_DESCRIPTION;

  return {
    title: input.title,
    description,
    alternates: { canonical: url },
    keywords: input.keywords ?? SEO_KEYWORDS,
    openGraph: {
      type: "website",
      url,
      siteName: SITE_NAME,
      title: input.title,
      description,
      locale: "ru_RU",
    },
    twitter: {
      card: "summary_large_image",
      title: input.title,
      description,
    },
    robots: input.noIndex
      ? { index: false, follow: false, nocache: true }
      : {
          index: true,
          follow: true,
          googleBot: {
            index: true,
            follow: true,
            "max-snippet": -1,
            "max-image-preview": "large",
            "max-video-preview": -1,
          },
        },
  };
}
